"""Static checks that the frontend and backend agree (no browser needed)."""
import re
import unittest
from pathlib import Path

from app.core import Router
from app.handlers import register_routes

FRONTEND = Path(__file__).resolve().parents[2] / "frontend"
JS = (FRONTEND / "app.js").read_text(encoding="utf-8")
HTML = (FRONTEND / "index.html").read_text(encoding="utf-8")

TERM = r'(?:"[^"]*"|[A-Za-z_][\w.]*(?:\([^)]*\))?)'
CALL = re.compile(r'\bapi\(\s*"(GET|POST|PUT|PATCH|DELETE)"\s*,\s*(' + TERM + r'(?:\s*\+\s*' + TERM + r')*)')

# SPA routes, mirrored from parseRoute() in app.js
UI_ROUTES = [re.compile(p) for p in (r"^#/login$", r"^#/projects$", r"^#/projects/[\w-]+$", r"^#/models/[\w-]+$")]


def frontend_calls():
    out = []
    for m in CALL.finditer(JS):
        path = ""
        for term in re.split(r"\s*\+\s*(?=(?:\"|[A-Za-z_]))", m.group(2)):
            term = term.strip()
            path += term[1:-1] if term.startswith('"') else "X1"
        out.append((m.group(1), path.split("?")[0]))
    return out


class TestContract(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.router = Router()
        register_routes(cls.router)

    def test_frontend_found_calls(self):
        self.assertGreaterEqual(len(frontend_calls()), 14)

    def test_every_frontend_api_call_hits_a_real_route_with_right_method(self):
        for method, path in frontend_calls():
            try:
                self.router.match(method, path)
            except Exception as e:  # noqa: BLE001
                self.fail("frontend calls %s %s but backend says: %s" % (method, path, e))

    def test_every_frontend_call_to_protected_route_would_send_token(self):
        # all calls go through api(), which attaches the bearer token when present
        self.assertEqual(len(re.findall(r"fetch\(", JS)), 1)
        self.assertIn('headers["Authorization"] = "Bearer " + t', JS)

    def test_navigation_targets_resolve(self):
        targets = re.findall(r'href="(#/[^"]*)"', JS) + re.findall(r'location\.hash\s*=\s*"(#/[^"]*)"(?:\s*\+\s*[\w.]+)?', JS)
        self.assertGreater(len(targets), 8)
        dyn = re.compile(r"'\s*\+\s*esc\([^)]*\)\s*\+\s*'")
        checked = 0
        for t in targets:
            concrete = dyn.sub("X1", t)
            if concrete.endswith("/"):  # prefix of `"#/projects/" + id`
                concrete += "X1"
            self.assertTrue(any(r.match(concrete) for r in UI_ROUTES), "%s -> %s" % (t, concrete))
            checked += 1
        self.assertGreaterEqual(checked, 9)

    def test_every_data_action_has_a_handler(self):
        used = set(re.findall(r'data-action="([\w-]+)"', JS))
        handlers = set(re.findall(r'^\s{4}"?([\w-]+)"?:\s*function', JS, re.M))
        self.assertEqual(used - handlers, set(), "buttons/forms with no handler")
        self.assertEqual(handlers - used, set(), "handlers never wired to any element")

    def test_every_element_id_read_by_js_exists_in_markup(self):
        wanted = set(re.findall(r'(?:val|getElementById|busy)\("([\w-]+)"', JS))
        defined = set(re.findall(r'\bid="([\w-]+)"', JS)) | set(re.findall(r'\bid="([\w-]+)"', HTML))
        self.assertEqual(wanted - defined, set())

    def test_index_references_existing_assets(self):
        for ref in re.findall(r'(?:src|href)="/([\w.\-]+)"', HTML):
            if ref != "config.js":  # generated by the server
                self.assertTrue((FRONTEND / ref).is_file(), ref)

    def test_no_inline_script_or_style_that_the_csp_would_block(self):
        self.assertNotRegex(HTML, r"<script(?![^>]*\bsrc=)[^>]*>")
        self.assertNotRegex(HTML + JS, r'\sstyle="')
        self.assertNotRegex(JS, r'\son(?:click|submit|change|load)="')

    def test_backend_routes_not_used_by_ui_are_known(self):
        used = {(m, p) for m, p in frontend_calls()}
        unused = []
        for m, pat in self.router.patterns():
            probe = re.sub(r"\{\w+\}", "X1", pat)
            if (m, probe) not in used:
                unused.append((m, pat))
        self.assertEqual(sorted(unused), sorted([
            ("GET", "/api/health"), ("GET", "/api/auth/me"), ("GET", "/api/datasets/{id}"), ("GET", "/api/jobs/{id}"),
        ]))


if __name__ == "__main__":
    unittest.main()
